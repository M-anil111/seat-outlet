<h2>How to use the artists on tour list</h2>
<ol>
  <li>Tap a letter in the A to Z bar to see artists whose names start with it, or choose All.</li>
  <li>Open an artist to see every upcoming date, with the venue and city.</li>
  <li>On a date, compare sections and prices on the seat map before you decide.</li>
  <li>Filter by genre from the <a href="/country-music-tickets">country</a>, <a href="/hip-hop-tickets">hip hop</a> and <a href="/pop-rock-concert-tickets">pop and rock</a> pages if you want a style rather than a name.</li>
</ol>
<p>Bands whose name starts with "The" are usually listed under the next word, so try both letters.</p>

<h2>About ticket prices and orders</h2>
<p>Seat Outlet compares listings from many sellers on a resale marketplace, so prices are set by sellers and can be above or below face value. Orders are fulfilled through the TicketNetwork marketplace and covered by its 100% guarantee; <a href="/worry-free-guarantee">see what the guarantee covers</a>. Not sure how it works? Read <a href="/how-to-buy-tickets-online">how to buy tickets online</a>.</p>

