<h2>Using a Tickets Promo Code at Checkout</h2>
<ol>
  <li><strong>Pick your event and seats.</strong> Open an event from the <a href="/buy-tickets-online">buy tickets online</a> listing and choose your section and quantity.</li>
  <li><strong>Check the code's conditions.</strong> Look at the order minimum or any other terms shown with the code.</li>
  <li><strong>Copy the code.</strong> Use the Copy button on the code card so you do not mistype it.</li>
  <li><strong>Enter it at checkout.</strong> Paste it into the promo code field when one is offered.</li>
  <li><strong>Review your total.</strong> Confirm the price before you pay.</li>
</ol>
<div class="so-callout">
  <p><strong>Good to know:</strong> Codes apply only where the checkout accepts them, and savings vary by event. If a code is not accepted, check the spelling and the order minimum, then try again or contact support.</p>
</div>

<h2>Why a Tickets Promo Code Might Not Work</h2>
<p>Codes can fail for ordinary reasons, and most of them are easy to fix. If your tickets promo code is rejected, go through this list first.</p>
<ul>
  <li><strong>Typing errors.</strong> Copy and paste the code instead of typing it. Codes may be case sensitive.</li>
  <li><strong>The order is too small.</strong> Some codes only apply once the order reaches a minimum amount.</li>
  <li><strong>The code has expired.</strong> Limited-time offers end, and the terms say when.</li>
  <li><strong>One code per order.</strong> Our terms on this page say only one promo code can be used per order, and codes cannot be combined with other offers.</li>
  <li><strong>The event is not included.</strong> A code may not apply to every event or listing.</li>
</ul>
<p>Still stuck? Contact <a href="/ticket-customer-service">ticket customer service</a> with your order details, and the team will take a look.</p>

<h2>Other Ways to Save Besides a Tickets Promo Code</h2>
<p>A code is only one way to lower what you pay. Because Seat Outlet is a resale marketplace, sellers set their own prices, and the same event can have listings at many price points. That means comparing can save as much as a tickets promo code does.</p>
<h3>Compare listings</h3>
<p>Open the event page and look at several sections. A seat a few rows back can cost less than one near the front and still give a good view.</p>
<h3>Stay flexible on the date</h3>
<p>A weeknight show or a less popular game often has lower prices than a weekend headliner. If you can move your plans, check more than one date.</p>
<h3>Look at the total</h3>
<p>Compare the full amount at checkout, not only the price on the listing. That is the number that matters when you decide.</p>
<p>For more ideas, see our <a href="/ticket-deals">ticket deals</a> page, which focuses on ways to find value on concert and sports tickets. We do not promise that any ticket is the lowest price available, since prices change with demand.</p>

