<h2>Protected Orders, With or Without a Tickets Promo Code</h2>
<p>A discount does not change your protection. Every order is covered by our <a href="/worry-free-guarantee">worry-free guarantee</a> and <a href="/ticket-buyer-protection">ticket buyer protection</a> policy, whether you used a code or not. Tickets are guaranteed valid and authentic, and if an event is canceled and not rescheduled, you receive a full refund for your ticket purchase.</p>
<p>Be careful with codes from unknown sources. The FTC explains how to spot problems in its <a href="https://consumer.ftc.gov/articles/online-shopping" target="_blank" rel="noopener">online shopping advice</a>, and a good rule is to rely on codes published on the site you are buying from. For an outside overview of how promotional coupons work in general, see Wikipedia on <a href="https://en.wikipedia.org/wiki/Coupon" target="_blank" rel="noopener">coupons</a>.</p>
