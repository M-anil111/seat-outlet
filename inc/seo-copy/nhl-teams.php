<h2>How to use the NHL teams list</h2>
<ol>
  <li>Pick a letter, or choose All to see every NHL team currently listed.</li>
  <li>Open a team to see its games with date, opponent and arena.</li>
  <li>Compare sections on the seat map, from glass seats to the upper bowl.</li>
  <li>Check the event page for the puck drop time.</li>
</ol>
<p>Hockey arenas are compact, so most seats keep you close to the ice.</p>

<h2>About ticket prices and orders</h2>
<p>Seat Outlet compares listings from many sellers on a resale marketplace, so prices are set by sellers and can be above or below face value. Orders are fulfilled through the TicketNetwork marketplace and covered by its 100% guarantee; <a href="/worry-free-guarantee">see what the guarantee covers</a>. Not sure how it works? Read <a href="/how-to-buy-tickets-online">how to buy tickets online</a>.</p>

