<h2>How to use the MLS teams list</h2>
<ol>
  <li>Pick a letter, or choose All to see every MLS team currently listed.</li>
  <li>Open a team to see its matches with date, opponent and stadium.</li>
  <li>Compare sections on the seat map, from midfield seats to areas behind the goals.</li>
  <li>Check the event page for the kickoff time.</li>
</ol>
<p>Midfield seats show the shape of the whole match, while seats behind the goals are closer to the supporters.</p>

<h2>About ticket prices and orders</h2>
<p>Seat Outlet compares listings from many sellers on a resale marketplace, so prices are set by sellers and can be above or below face value. Orders are fulfilled through the TicketNetwork marketplace and covered by its 100% guarantee; <a href="/worry-free-guarantee">see what the guarantee covers</a>. Not sure how it works? Read <a href="/how-to-buy-tickets-online">how to buy tickets online</a>.</p>

